/**
 * Откуда человек: субъект РФ (или страна), а не деревня / район.
 * Место рождения важнее прописки.
 */

function normalizePlace(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[—–−]/g, "-")
    .replace(/[^а-яa-z0-9-]+/gi, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function containsPhrase(hay, needle) {
  const n = normalizePlace(needle);
  if (!n || n.length < 3) return false;
  return ` ${hay} `.includes(` ${n} `);
}

function obl(adj) {
  const gen = adj.replace(/ая$/i, "ой");
  return {
    name: `${adj} область`,
    aliases: [
      `${adj} область`,
      `${gen} области`,
      `${adj} обл`,
      `${gen} обл`,
    ],
  };
}

function krai(adj) {
  const gen = adj.replace(/кий$/i, "кого").replace(/ий$/i, "ого").replace(/ый$/i, "ого");
  return {
    name: `${adj} край`,
    aliases: [`${adj} край`, `${gen} края`, `${adj} кр`, `${gen} кр`],
  };
}

function republic(name, extra = []) {
  return {
    name: name.startsWith("Республика") || name.includes("Республика")
      ? name
      : `Республика ${name}`,
    aliases: [
      `республика ${name.replace(/^Республика\s+/i, "")}`,
      `республики ${name.replace(/^Республика\s+/i, "")}`,
      `респ ${name.replace(/^Республика\s+/i, "")}`,
      `р ${name.replace(/^Республика\s+/i, "")}`,
      name.replace(/^Республика\s+/i, ""),
      ...extra,
    ],
  };
}


const NEEDLES = SUBJECTS.flatMap((s) =>
  s.aliases.map((alias) => ({
    name: s.name,
    needle: normalizePlace(alias),
  }))
).sort((a, b) => b.needle.length - a.needle.length);

export function resolveRegion(text) {
  const hay = normalizePlace(text);
  if (!hay) return null;
  for (const { name, needle } of NEEDLES) {
    if (needle && containsPhrase(hay, needle)) return name;
  }
  return null;
}

/** Откуда приехал: сначала место рождения, иначе регистрация. */
export function originRegion(birthPlace, registrationAddress) {
  return (
    resolveRegion(birthPlace) ||
    resolveRegion(registrationAddress) ||
    "Не указано"
  );
}


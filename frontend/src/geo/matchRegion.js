function normName(s) {
  return String(s ?? "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[—–−]/g, "-")
    .replace(/^республика\s+/g, "")
    .replace(/автономн[а-яё]*\s+округ/g, "ао")
    .replace(/\s+/g, " ")
    .trim();
}


export function matchGeoToOurs(geoName) {
  const n = normName(geoName);
  if (!n) return null;
  if (EXTRA[n]) return EXTRA[n];
  const exact = CANONICAL_REGIONS.find((o) => normName(o) === n);
  if (exact) return exact;
  return (
    CANONICAL_REGIONS.find((o) => {
      const on = normName(o);
      return on === n || on.startsWith(`${n} `) || n.startsWith(`${on} `);
    }) ?? null
  );
}
